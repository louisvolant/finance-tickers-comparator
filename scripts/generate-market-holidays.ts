// Authoring-time generator for `src/lib/marketHolidays.json`.
//
// This is the only remaining consumer of `date-holidays`. The generated table is
// committed and read directly by the runtime, which is why the Worker bundle no
// longer contains date-holidays, moment, moment-timezone, astronomia or tldts.
//
// Run with `npm run generate:market-holidays`. The build check
// (`scripts/ensure-market-holidays.ts`) calls `generateMarketHolidays()` only
// when the committed table is stale or no longer covers next year.

import fs from 'node:fs';
import path from 'node:path';
import { easterSunday, MARKET_CALENDARS } from '../src/lib/marketCalendar.ts';
import type { MarketHolidaysFile } from '../src/lib/marketHolidays.ts';

const OUTPUT_FILE = path.join(process.cwd(), 'src/lib/marketHolidays.json');

/** Years generated by a manual run: current year + 14 (inclusive). */
const DEFAULT_YEARS = 15;

const pad = (n: number) => String(n).padStart(2, '0');

export interface GenerateMarketHolidaysOptions {
  fromYear?: number;
  toYear?: number;
  years?: number;
}

/**
 * Compute the closed dates of every venue over the requested year window.
 *
 * The rules are the ones the runtime used before the table existed:
 * - country public holidays from date-holidays;
 * - minus the venue-specific `ignoredHolidays`;
 * - plus Good Friday / Easter Monday when the venue observes them;
 * - plus fixed `closedOn` dates (MM-DD).
 *
 * Keeping the filtering here (and not at runtime) is what allows the runtime to
 * be a simple lookup.
 */
export async function generateMarketHolidays(
  options: GenerateMarketHolidaysOptions = {}
): Promise<MarketHolidaysFile> {
  // Lazy import: the build check must not load the library when the committed
  // table is still fresh.
  const { default: Holidays } = await import('date-holidays');

  const currentYear = new Date().getUTCFullYear();
  const fromYear = options.fromYear ?? currentYear;
  const toYear = options.toYear ?? fromYear + (options.years ?? DEFAULT_YEARS) - 1;

  const providers = new Map<string, any>();
  const holidays: Record<string, string[]> = {};

  for (const [timezone, calendar] of Object.entries(MARKET_CALENDARS)) {
    let provider = providers.get(calendar.country);
    if (!provider) {
      provider = new Holidays(calendar.country, { languages: ['en'] });
      providers.set(calendar.country, provider);
    }

    const closed = new Set<string>();

    for (let year = fromYear; year <= toYear; year++) {
      for (const holiday of provider.getHolidays(year)) {
        if (holiday.type !== 'public') continue;
        if (calendar.ignoredHolidays?.includes(holiday.name)) continue;
        closed.add(String(holiday.date).slice(0, 10));
      }

      const easter = easterSunday(year);
      const shift = (days: number) => {
        const date = new Date(easter.getTime() + days * 86_400_000);
        return `${date.getUTCFullYear()}-${pad(date.getUTCMonth() + 1)}-${pad(date.getUTCDate())}`;
      };

      if (calendar.goodFriday) closed.add(shift(-2));
      if (calendar.easterMonday) closed.add(shift(1));

      for (const monthDay of calendar.closedOn ?? []) {
        closed.add(`${year}-${monthDay}`);
      }
    }

    holidays[timezone] = Array.from(closed).sort();
  }

  return {
    generatedAt: new Date().toISOString().slice(0, 10),
    coverage: { from: fromYear, to: toYear },
    holidays,
  };
}

export function writeMarketHolidays(data: MarketHolidaysFile, file: string = OUTPUT_FILE): void {
  fs.writeFileSync(file, `${JSON.stringify(data, null, 2)}\n`, 'utf-8');
}

async function main() {
  const data = await generateMarketHolidays();
  writeMarketHolidays(data);
  console.log(
    `Wrote ${OUTPUT_FILE} (${data.coverage.from}-${data.coverage.to}, ` +
      `${Object.keys(data.holidays).length} venues)`
  );
}

const isDirectRun =
  !!process.argv[1] && /generate-market-holidays\.(ts|js|mjs)$/.test(process.argv[1]);

if (isDirectRun) {
  main().catch((err) => {
    console.error('Holiday generation failed:', err);
    process.exit(1);
  });
}
